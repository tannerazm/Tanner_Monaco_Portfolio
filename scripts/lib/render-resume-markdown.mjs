// Turns the site's resume data into the markdown that md-to-pdf renders.
//
// This is a pure function on purpose: no filesystem, no esbuild, no puppeteer.
// scripts/build-resume.mjs does the loading and the PDF call; everything about
// what the resume SAYS lives here, where a test can pin it.

const SEP = " &nbsp;|&nbsp; ";
const DOT = " &nbsp;&middot;&nbsp; ";

// "https://www.linkedin.com/in/tannerazm/" -> "linkedin.com/in/tannerazm"
export function linkLabel(url) {
  return url.replace(/^https?:\/\//, "").replace(/^www\./, "").replace(/\/$/, "");
}

function link(url) {
  return `[${linkLabel(url)}](${url})`;
}

// Groups sharing a pdfLabel collapse onto one line, keeping first-seen order.
export function mergeSkillGroups(groups) {
  const merged = [];
  const byLabel = new Map();
  for (const group of groups) {
    const label = group.pdfLabel ?? group.label;
    const existing = byLabel.get(label);
    if (existing) {
      existing.skills.push(...group.skills);
    } else {
      const entry = { label, skills: [...group.skills] };
      byLabel.set(label, entry);
      merged.push(entry);
    }
  }
  return merged;
}

// A bullet is either a plain string (same text both places) or an object whose
// `pdf` field overrides the text. `pdf: null` means "site only, skip here".
export function pdfBullets(bullets) {
  return bullets
    .map((b) => (typeof b === "string" ? b : b.pdf === undefined ? b.text : b.pdf))
    .filter((text) => typeof text === "string" && text.length > 0);
}

export function selectProjects(projects, slugs) {
  return slugs.map((slug) => {
    const project = projects.find((p) => p.slug === slug);
    if (!project) {
      throw new Error(
        `RESUME_PDF_PROJECT_SLUGS names "${slug}", which is not in PROJECTS.`,
      );
    }
    return project;
  });
}

export function renderResumeMarkdown({ contact, resume, projects = [] }) {
  const out = [];

  out.push("<!-- Generated by scripts/build-resume.mjs. Do not edit by hand.");
  out.push("     Edit src/data/resume.ts, projects.ts, or contact.ts instead,");
  out.push("     then run: npm run build:resume -->");
  out.push("");

  // Header
  out.push(`# ${contact.name}`);
  out.push(`**${resume.title}**<br>`);
  out.push([contact.phone, contact.email, contact.location].join(SEP) + "<br>");
  out.push(
    [
      `[${contact.site}](${contact.siteUrl})`,
      link(contact.linkedin),
      link(contact.github),
    ].join(SEP),
  );
  out.push("");

  out.push("## Summary");
  out.push(resume.summary);
  out.push("");

  out.push("## Technical Skills");
  const skillLines = mergeSkillGroups(resume.skillGroups).map(
    (group) => `**${group.label}:** ${group.skills.join(", ")}`,
  );
  // <br> joins the lines into one tight block instead of separate paragraphs.
  out.push(skillLines.join("<br>\n"));
  out.push("");

  out.push("## Experience");
  out.push("");
  for (const role of resume.experience) {
    out.push(
      `**${role.company}**${DOT}${role.title}${DOT}${role.location}${DOT}*${role.start} to ${role.end}*`,
    );
    for (const bullet of pdfBullets(role.bullets)) out.push(`- ${bullet}`);
    out.push("");
  }

  if (projects.length > 0) {
    out.push("## Projects");
    out.push("");
    for (const project of projects) {
      out.push(
        `**${project.name}**${DOT}[${linkLabel(project.liveUrl)}](${project.liveUrl})${DOT}*${project.date}*`,
      );
      out.push(`- ${project.resumeLine ?? project.tagline}`);
      out.push("");
    }
  }

  out.push("## Education");
  out.push(
    resume.education
      .map((edu) => {
        const parts = [`**${edu.school}**`, edu.credential];
        if (edu.detail) parts.push(edu.detail);
        return parts.join(DOT) + `${DOT}*Graduated ${edu.date}*`;
      })
      .join("<br>\n"),
  );
  out.push("");

  out.push(
    `*Learn more about me and my experience at ${link(contact.linkedin)}${SEP}${contact.phone}${SEP}${contact.email}${SEP}[${contact.site}](${contact.siteUrl})*`,
  );
  out.push("");

  return out.join("\n");
}
